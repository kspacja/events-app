"""Reads the PRNG localities export (XLSX) with the standard library only.

Usage:
  python3 scripts/prng/localities.py headers <file.xlsx>
  python3 scripts/prng/localities.py json <file.xlsx> <out.json>
  python3 scripts/prng/localities.py sample <file.xlsx> <out.ts>
"""

import json
import math
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
KINDS = {'miasto': 'city', 'wieś': 'village', 'osada': 'settlement', 'kolonia': 'colony'}

COLUMNS = {
    'id': 'identyfikator zewnętrzny',
    'name': 'nazwa główna',
    'kind': 'rodzaj obiektu',
    'commune': 'gmina',
    'county': 'powiat',
    'voivodeship': 'województwo',
    'coords': 'współrzędne geograficzne',
}

# Sample for the mocks: every city, villages near Wrocław, a few same-name villages for the hints
WROCLAW = (51.1079, 17.0385)
NEAR_WROCLAW_KM = 40
SAME_NAME_SAMPLE = 'Nowa Wieś'


def shared_strings(zf):
    strings = []
    with zf.open('xl/sharedStrings.xml') as f:
        for _, el in ET.iterparse(f):
            if el.tag == NS + 'si':
                strings.append(''.join(t.text or '' for t in el.iter(NS + 't')))
                el.clear()
    return strings


def col_index(ref):
    letters = re.match(r'[A-Z]+', ref).group(0)
    n = 0
    for ch in letters:
        n = n * 26 + ord(ch) - 64
    return n - 1


def rows(path):
    with zipfile.ZipFile(path) as zf:
        strings = shared_strings(zf)
        with zf.open('xl/worksheets/sheet1.xml') as f:
            for _, el in ET.iterparse(f):
                if el.tag != NS + 'row':
                    continue
                row = {}
                for c in el.iter(NS + 'c'):
                    v = c.find(NS + 'v')
                    if v is None:
                        is_ = c.find(NS + 'is')
                        text = ''.join(t.text or '' for t in is_.iter(NS + 't')) if is_ is not None else ''
                    elif c.get('t') == 's':
                        text = strings[int(v.text)]
                    else:
                        text = v.text or ''
                    row[col_index(c.get('r'))] = text
                el.clear()
                yield [row.get(i, '') for i in range(max(row, default=-1) + 1)]


def dms_to_decimal(text):
    """PRNG writes a point as 51°06'28" 17°02'18" (lat lng); the import needs decimal degrees."""
    parts = [float(p) for p in re.findall(r'\d+(?:\.\d+)?', text)]
    if len(parts) != 6:
        raise ValueError(f'unexpected coordinates {text!r}')
    return tuple(round(d + m / 60 + s / 3600, 5) for d, m, s in (parts[:3], parts[3:]))


def localities(path):
    it = rows(path)
    header = next(it)
    idx = {key: header.index(col) for key, col in COLUMNS.items()}
    for r in it:
        r = r + [''] * (len(header) - len(r))
        kind = KINDS.get(r[idx['kind']])
        if kind is None or not r[idx['id']]:
            continue
        lat, lng = dms_to_decimal(r[idx['coords']])
        yield {
            'id': r[idx['id']].zfill(7),
            'name': r[idx['name']],
            'kind': kind,
            # "Kobierzyce-gmina wiejska" -> "Kobierzyce"
            'commune': r[idx['commune']].split('-gmina ')[0],
            'county': r[idx['county']],
            'voivodeship': r[idx['voivodeship']],
            'lat': lat,
            'lng': lng,
        }


def km_between(a, b):
    lat1, lng1, lat2, lng2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lng2 - lng1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def in_sample(loc):
    return (
        loc['kind'] == 'city'
        or loc['name'] == SAME_NAME_SAMPLE
        or km_between(WROCLAW, (loc['lat'], loc['lng'])) <= NEAR_WROCLAW_KM
    )


def ts_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_sample(path, out):
    sample = sorted((l for l in localities(path) if in_sample(l)), key=lambda l: l['id'])
    lines = [
        '// Generated by scripts/prng/localities.py from the PRNG export; do not edit by hand.',
        "import type { Locality } from '@events/contract/localities';",
        '',
        'type Row = readonly [string, string, Locality[\'kind\'], string, string, string, number, number];',
        '',
        '// id (SIMC), name, kind, commune, county, voivodeship, lat, lng',
        'const ROWS: readonly Row[] = [',
    ]
    for l in sample:
        cells = [l['id'], l['name'], l['kind'], l['commune'], l['county'], l['voivodeship']]
        lines.append('  [' + ', '.join(ts_string(c) for c in cells) + f", {l['lat']}, {l['lng']}],")
    lines += [
        '];',
        '',
        'export const SAMPLE_LOCALITIES: readonly Locality[] = ROWS.map(',
        '  ([id, name, kind, commune, county, voivodeship, lat, lng]) => ({ id, name, kind, commune, county, voivodeship, lat, lng }),',
        ');',
        '',
    ]
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f'{len(sample)} localities -> {out}')


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    cmd, path = argv[0], argv[1]
    if cmd == 'headers':
        it = rows(path)
        print(next(it))
        print(next(it))
    elif cmd == 'json':
        data = list(localities(path))
        with open(argv[2], 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False)
        print(f'{len(data)} localities -> {argv[2]}')
    elif cmd == 'sample':
        write_sample(path, argv[2])
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main(sys.argv[1:])
